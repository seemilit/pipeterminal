"""Read-only renderer boundary for substituting a C/C++ engine adapter."""

from collections.abc import Sequence
from typing import Protocol

from .model import Cursor, Damage, Line


class ScreenView(Protocol):
    rows: int
    cols: int
    history: Sequence[Line]

    def row_at(self, index: int) -> Line: ...
    def index_of(self, line_id: int) -> int | None: ...
    def take_damage(self) -> Damage: ...
    def invalidate(self) -> None: ...
    def selected_text(self, start: tuple[int, int], end: tuple[int, int]) -> str: ...


class TerminalEngineProtocol(Protocol):
    screen: ScreenView
    cursor: Cursor
    application_cursor: bool
    bracketed_paste: bool
    shell_ready: bool
    path_links_enabled: bool

    def feed(self, data: bytes) -> None: ...
    def note_input(self, data: bytes) -> None: ...
    def resize(self, rows: int, cols: int) -> None: ...
    def reset(self) -> None: ...
    def finish(self) -> None: ...
    def take_responses(self) -> bytes: ...
    def take_events(self) -> list[tuple[str, str]]: ...
